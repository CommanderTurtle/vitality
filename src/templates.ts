export function renderProjectViteConfig(base: string, inline: boolean, outDir: string, script: string): string {
  return [
    'import path from "node:path";',
    'import { fileURLToPath } from "node:url";',
    'import { defineConfig } from "vite";',
    'import { projectBuildPlugin, projectBuildEntry } from "./.vitality/build-adapter";',
    'const root = path.dirname(fileURLToPath(import.meta.url));',
    "const options = { root, base: " + JSON.stringify(base) + ", outDir: " + JSON.stringify(outDir) + ", script: " + JSON.stringify(script) + " };",
    "export default defineConfig({",
    "  root, base: options.base, publicDir: false,",
    "  plugins: [projectBuildPlugin(options)],",
    "  build: {",
    '    outDir: "dist", emptyOutDir: true,',
    inline ? "    assetsInlineLimit: Number.POSITIVE_INFINITY," : "    // assetsInlineLimit: Vite default,",
    '    rolldownOptions: { input: projectBuildEntry, output: { entryFileNames: ".vitality-entry.js" } },',
    "  },",
    "});",
    "",
  ].join("\n");
}

