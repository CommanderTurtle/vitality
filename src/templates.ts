export function renderViteConfig(base: string, inlineAssets: boolean, pages: string[]): string {
  const inputEntries = ["index.html", ...pages];
  const input = Object.fromEntries(inputEntries.map((file, index) => [
    index === 0 ? "index" : `page-${index}`,
    file,
  ]));
  const singlePageOutput = pages.length === 0
    ? `,
        output: {
          codeSplitting: false,
          entryFileNames: "assets/index.js",
          assetFileNames(asset) {
            const names = asset.names ?? [];
            return names.some((name) => name.endsWith(".css"))
              ? "assets/index.css"
              : "assets/[name][extname]";
          },
        }`
    : "";
  return `import path from "node:path";
import { fileURLToPath } from "node:url";
import { defineConfig } from "vite";

const root = path.dirname(fileURLToPath(import.meta.url));
const input = ${JSON.stringify(input, null, 2)};

export default defineConfig({
  root,
  base: ${JSON.stringify(base)},
  publicDir: "public",
  build: {
    outDir: "dist",
    emptyOutDir: true,
    cssCodeSplit: false,
    modulePreload: false,
    ${inlineAssets ? "assetsInlineLimit: Number.POSITIVE_INFINITY," : "// assetsInlineLimit: Vite default,"}
    rolldownOptions: {
      input: Object.fromEntries(
        Object.entries(input).map(([name, file]) => [name, path.resolve(root, file)]),
      )${singlePageOutput}
    },
  },
});
`;
}

